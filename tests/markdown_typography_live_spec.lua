local config = vim.fn.stdpath("config")
dofile(config .. "/init.lua")
vim.wait(3000, function()
  return vim.g.colors_name == "blue"
end, 50)
assert(vim.g.colors_name == "blue", "normal config should load the active Blue colorscheme")
local blue_normal = vim.api.nvim_get_hl(0, { name = "Normal", link = false })
local cobol = vim.api.nvim_create_buf(true, false)
vim.api.nvim_buf_set_name(cobol, "/tmp/typography-smoke.cob")
vim.bo[cobol].filetype = "cobol"
vim.api.nvim_win_set_buf(0, cobol)
local blue_statement = vim.api.nvim_get_hl(0, { name = "Statement", link = false })
local markdown = vim.api.nvim_create_buf(true, false)
vim.api.nvim_buf_set_name(markdown, "/tmp/typography-smoke.md")
vim.api.nvim_buf_set_lines(markdown, 0, -1, false, { "# Heading", "", "Text with `inline code`", "", "```lua", "print('dark block')", "```" })
vim.api.nvim_win_set_buf(0, markdown)
vim.cmd("setfiletype markdown")
vim.wait(100, function()
  return vim.wo.winhighlight:find("MdTypographyNormal", 1, true) ~= nil
end, 10)
assert(vim.bo.filetype == "markdown")
assert(vim.g.colors_name == "blue")
local ns = vim.api.nvim_get_hl_ns({ winid = 0 })
assert(ns ~= -1)
local paper = vim.api.nvim_get_hl(ns, { name = "MdTypographyNormal", link = false })
assert(paper.bg == 0xfaf9f5 and paper.fg == 0x303030)
assert(vim.api.nvim_get_hl(0, { name = "@markup.heading.1", link = false }).fg == 0x000087)
vim.api.nvim_win_set_buf(0, cobol)
vim.wait(50, function()
  return vim.wo.winhighlight == ""
end, 10)
assert(vim.bo.filetype == "cobol")
assert(vim.wo.winhighlight == "")
assert(vim.deep_equal(vim.api.nvim_get_hl(0, { name = "Normal", link = false }), blue_normal))
assert(vim.deep_equal(vim.api.nvim_get_hl(0, { name = "Statement", link = false }), blue_statement))
print("markdown_typography_live_config: OK (Blue retained; Markdown local; COBOL restored)")
vim.cmd("qa!")