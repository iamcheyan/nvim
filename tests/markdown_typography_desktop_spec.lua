local config = vim.fn.stdpath("config")
dofile(config .. "/init.lua")
vim.wait(5000, function()
  return vim.g.colors_name == "blue"
end, 50)
assert(vim.g.colors_name == "blue")
local markdown = vim.api.nvim_create_buf(true, false)
vim.api.nvim_buf_set_name(markdown, "/tmp/markdown-cursor.md")
vim.api.nvim_buf_set_lines(markdown, 0, -1, false, { "# Heading", "", "Prose paragraph", "", "```cobol", "DISPLAY 'dark code'", "```" })
vim.bo[markdown].filetype = "markdown"
vim.api.nvim_win_set_buf(0, markdown)
vim.api.nvim_exec_autocmds("FileType", { buffer = markdown })
vim.api.nvim_exec_autocmds("BufEnter", { buffer = markdown })
vim.api.nvim_exec_autocmds("BufWinEnter", { buffer = markdown })
require("markview").setup({ preview = { filetypes = { "markdown" } } })
require("markview.commands").Start()
require("markview.commands").attach(markdown)
vim.wait(100, function()
  return require("markview.state").buf_attached(markdown)
end, 10)
assert(require("markview.state").buf_attached(markdown))
local ns = vim.api.nvim_get_hl_ns({ winid = 0 })
local normal = vim.api.nvim_get_hl(ns, { name = "MdTypographyNormal", link = false })
assert(normal.bg == 0xfaf9f5 and normal.fg == 0x303030)
local markview = require("markview.highlights")
local typography = require("config.markdown_typography")
local palette = typography.palette()
markview.groups["1"] = function()
  return { { group_name = "MarkviewPalette1", value = { fg = palette.blue_dark, bg = palette.paper } } }
end
markview.setup()
local generated = markview.groups["1"]()
for _, item in ipairs(generated) do
  vim.api.nvim_set_hl(0, item.group_name, item.value)
end
local palette1 = vim.api.nvim_get_hl(0, { name = "MarkviewPalette1", link = false })
assert(palette1.bg == 0xfaf9f5)
local palette1_sign = vim.api.nvim_get_hl(0, { name = "MarkviewPalette1Sign", link = false })
assert(palette1_sign.fg ~= nil)
local code = vim.api.nvim_get_hl(0, { name = "MarkviewCode", link = false })
assert(code.bg == 1447 or code.bg == 0x202536, "Markview code remains dark")
print("markdown_typography_desktop_spec: OK")