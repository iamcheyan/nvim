local root = vim.fn.getcwd()
package.path = root .. "/lua/?.lua;" .. root .. "/lua/?/init.lua;" .. package.path

vim.cmd.colorscheme("blue")
local original = vim.api.nvim_get_hl(0, { name = "Normal", link = false })
local original_statement = vim.api.nvim_get_hl(0, { name = "Statement", link = false })
local original_heading = vim.api.nvim_get_hl(0, { name = "@markup.heading.1", link = false })
local typography = require("config.markdown_typography")
typography.setup()

local markdown = vim.api.nvim_create_buf(true, false)
vim.api.nvim_buf_set_name(markdown, "/tmp/markdown-typography.md")
vim.bo[markdown].filetype = "markdown"
local mdwin = vim.api.nvim_get_current_win()
vim.api.nvim_win_set_buf(mdwin, markdown)
vim.api.nvim_exec_autocmds("FileType", { buffer = markdown, modeline = false })

local palette = typography.palette()
local md_ns = vim.api.nvim_get_hl_ns({ winid = mdwin })
assert(md_ns ~= -1, "Markdown window should use an isolated highlight namespace")
local md_normal = vim.api.nvim_get_hl(md_ns, { name = "MdTypographyNormal", link = false })
assert(md_normal.bg == tonumber(palette.paper:sub(2), 16), "Markdown window palette must use warm paper")
assert(md_normal.fg == tonumber(palette.ink:sub(2), 16), "Markdown window palette must use book-text ink")
assert(vim.wo[mdwin].winhighlight:find("Normal:MdTypographyNormal", 1, true), "Markdown window must map Normal locally")
local md_syntax = vim.api.nvim_get_hl(0, { name = "@markup.heading.1", link = false })
assert(md_syntax.fg == tonumber(palette.blue_dark:sub(2), 16))
md_syntax = vim.api.nvim_get_hl(0, { name = "@markup.raw.block", link = false })
assert(md_syntax.bg == tonumber(palette.code_bg:sub(2), 16))
md_syntax = vim.api.nvim_get_hl(0, { name = "@markup.raw.inline", link = false })
assert(md_syntax.fg == tonumber(palette.red:sub(2), 16))

local cobol = vim.api.nvim_create_buf(true, false)
vim.api.nvim_buf_set_name(cobol, "/tmp/ordinary-program.cob")
vim.bo[cobol].filetype = "cobol"
vim.api.nvim_win_set_buf(mdwin, cobol)
vim.api.nvim_exec_autocmds("BufWinLeave", { buffer = markdown, modeline = false })
vim.wait(50, function() return vim.wo[mdwin].winhighlight == "" end, 5)
assert(vim.wo[mdwin].winhighlight == "", "leaving Markdown must restore the window's original highlight mapping")
assert(vim.deep_equal(vim.api.nvim_get_hl(0, { name = "Normal", link = false }), original), "Markdown theme must not change global Normal")
assert(vim.deep_equal(vim.api.nvim_get_hl(0, { name = "Statement", link = false }), original_statement), "Markdown theme must leave code syntax colors unchanged")
assert(vim.deep_equal(vim.api.nvim_get_hl(0, { name = "@markup.heading.1", link = false }), original_heading), "leaving Markdown must restore the original Blue heading highlight")

local otherwin = vim.api.nvim_open_win(markdown, false, { split = "right" })
vim.api.nvim_exec_autocmds("BufWinEnter", { buffer = markdown, modeline = false })
assert(vim.wo[otherwin].winhighlight:find("Normal:MdTypographyNormal", 1, true), "every Markdown window should get its local palette")
vim.api.nvim_win_close(otherwin, true)
vim.api.nvim_win_set_buf(mdwin, cobol)
vim.api.nvim_exec_autocmds("BufWinLeave", { buffer = markdown, modeline = false })
vim.wait(20, function() return vim.wo[mdwin].winhighlight == "" end, 5)
assert(vim.wo[mdwin].winhighlight == "", "closing or leaving Markdown must not leak window overrides")
assert(vim.deep_equal(vim.api.nvim_get_hl(0, { name = "Normal", link = false }), original), "global Blue Normal must remain intact")
print("markdown_typography_spec: OK")